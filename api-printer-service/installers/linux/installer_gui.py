class TerminalInstaller:
    BOLD  = "\033[1m"
    BLUE  = "\033[34m"
    GREEN = "\033[32m"
    RED   = "\033[31m"
    GRAY  = "\033[90m"
    RST   = "\033[0m"

    def run(self):
        self._header()
        self._page_welcome()
        self._page_checks()
        install_dir = self._page_destination()
        self._page_install(install_dir)
        self._page_finish(install_dir)

    def _header(self):
        os.system("clear 2>/dev/null || cls 2>/dev/null || true")
        print(f"{self.BOLD}{self.BLUE}"
              f"╔══════════════════════════════════════════╗\n"
              f"║   API Printer Service {VERSION:<20}║\n"
              f"╚══════════════════════════════════════════╝"
              f"{self.RST}\n")

    def _page_welcome(self):
        print(f"{self.BOLD}Welcome{self.RST}\n")
        print(
            "This wizard will install the API Printer Service on your system.\n\n"
            "The service provides a local REST API on port 5058 that allows\n"
            "POSAwesome to print receipts to CUPS thermal printers.\n\n"
            "What will be installed:\n"
            "  • Service binary →  chosen install directory (self-contained)\n"
            "  • Systemd unit   →  auto-starts on boot\n"
        )
        input("Press Enter to continue… ")
        print()

    def _page_checks(self) -> None:
        print(f"{self.BOLD}System compatibility{self.RST}\n")
        checks = _run_system_checks()
        for c in checks:
            icon = {
                "ok":   f"{self.GREEN}✓{self.RST}",
                "warn": f"{self.BOLD}⚠{self.RST}",
                "fail": f"{self.RED}✗{self.RST}",
            }[c.status]
            line = f"  {icon}  {c.name:<18}"
            if c.message:
                line += f"  {self.GRAY}{c.message}{self.RST}"
            print(line)
        print()

        if _checks_blocking(checks):
            print(f"{self.RED}✗  The system is not suitable for installation.{self.RST}")
            print("   Address the failing check(s) above and run the installer again.\n")
            sys.exit(1)

        if _checks_warnings(checks):
            ans = input("Warnings were reported. Continue anyway? [y/N]: ").strip().lower()
            if ans != "y":
                print("Installation cancelled.")
                sys.exit(0)
            print()

    def _page_destination(self) -> str:
        print(f"{self.BOLD}Install location{self.RST}\n")
        answer = input(
            f"Install directory [{DEFAULT_INSTALL_DIR}]: "
        ).strip()
        install_dir = answer or DEFAULT_INSTALL_DIR
        print(f"\nWill install to: {self.BOLD}{install_dir}{self.RST}")
        confirm = input("Proceed? [Y/n]: ").strip().lower()
        if confirm and confirm != "y":
            print("Installation cancelled.")
            sys.exit(0)
        print()
        return install_dir

    def _page_install(self, install_dir: str):
        print(f"{self.BOLD}Installing…{self.RST}\n")

        def log(msg):
            print(f"  {self.GRAY}{msg}{self.RST}")

        def progress(pct, label):
            bar_width = 40
            filled = int(bar_width * pct / 100)
            bar = "█" * filled + "░" * (bar_width - filled)
            print(f"\r  [{bar}] {pct:>3}%  {label:<40}", end="", flush=True)

        print()
        try:
            run_install_steps(install_dir, log, progress)
            print()
        except Exception as exc:
            print()
            print(f"\n{self.RED}✗  Error: {exc}{self.RST}")
            sys.exit(1)

    def _page_finish(self, install_dir: str):
        print(f"\n{self.BOLD}{self.GREEN}Installation complete ✓{self.RST}\n")
        print(
            f"  Install directory : {install_dir}\n"
            f"  Port              : http://localhost:5058\n"
            f"  Health check      : curl http://localhost:5058/health\n"
            f"  Logs              : {LOG_FILE}\n"
            f"  GUI launcher      : {LAUNCHER_PATH}\n"
            f"                      (also available from the application menu)\n\n"
            f"  systemctl status  api-printer.service\n"
            f"  systemctl stop    api-printer.service\n"
        )


