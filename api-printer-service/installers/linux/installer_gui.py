def _pkexec_relaunch() -> None:
    """
    Re-launch this binary as root via pkexec.

    We do NOT pass --setenv (only supported in pkexec ≥ 0.106; older
    versions treat it as the executable name, producing "Cannot run
    program --setenv").  Instead, _restore_display_from_proc() is called
    once we are root: it walks up the /proc tree and reads DISPLAY /
    WAYLAND_DISPLAY from pkexec's own environ entry, which still holds
    the original user-session variables because pkexec was exec-ed from
    the user's terminal.
    """
    os.execvp("pkexec", ["pkexec", sys.executable] + sys.argv[1:])


if __name__ == "__main__":
    if os.geteuid() != 0:
        # Not root — escalate with pkexec (preserves Wayland/X11 vars)
        # or tell the user to use sudo.
        if shutil.which("pkexec"):
            _pkexec_relaunch()   # replaces the current process
        sys.exit(
            "This installer must be run as root.\n"
            "Run:  sudo ./api-printer-installer-linux"
        )

    if _has_display():
        InstallerApp().run()
    else:
        TerminalInstaller().run()
