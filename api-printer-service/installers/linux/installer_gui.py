# Shared installation logic (used by both GUI and terminal modes)
# =============================================================================

def run_install_steps(install_dir: str, log_fn, progress_fn):
    """
    Execute each install step.
      log_fn(msg)              — called to append a log line
      progress_fn(pct, label)  — called to update progress (0–100)
    Raises on error.
    """
    steps = [
        (  5, "Stopping existing service",         _step_stop_existing),
        ( 15, "Creating directories",              _step_mkdir),
        ( 30, "Installing service binary",         _step_copy_service),
        ( 45, "Installing GUI",                    _step_copy_gui),
        ( 60, "Installing GUI dependencies",       _step_apt_deps),
        ( 75, "Registering desktop launcher",      _step_desktop),
        ( 85, "Granting GUI service permissions",  _step_polkit),
        ( 95, "Registering systemd service",       _step_systemd),
        (100, "Done",                              None),
    ]
    for pct, label, fn in steps:
        progress_fn(pct, label + "…")
        log_fn(f"► {label}")
        if fn:
            fn(install_dir, log_fn)
    log_fn("\n✓  Installation complete!")


def _step_stop_existing(install_dir, log):
    """
    Stop any previously-installed instance so we can overwrite its binary.

    Linux returns ETXTBSY (Errno 26, "Text file busy") on any attempt to
    open a running executable for writing, so an upgrade-install on top
    of a live service fails at the copy step without this.  Idempotent:
    succeeds silently on fresh installs where the unit does not yet exist.
    """
    env = _system_env()

    if shutil.which("systemctl"):
        # `systemctl cat` exits non-zero when the unit file is absent —
        # cheaper than parsing list-units and works before daemon-reload.
        has_unit = subprocess.run(
            ["systemctl", "cat", "api-printer.service"],
            capture_output=True, text=True, env=env,
        ).returncode == 0
        if has_unit:
            log("  systemctl stop api-printer.service")
            r = subprocess.run(
                ["systemctl", "stop", "api-printer.service"],
                capture_output=True, text=True, env=env,
            )
            for line in (r.stdout + r.stderr).splitlines():
                if line.strip():
                    log(f"    {line}")

    # Fallback: if the binary at the target path is still held by a
    # non-systemd process (manual launch, orphaned child), SIGTERM it so
    # the copy step can succeed.  fuser is part of psmisc and not always
    # installed, so we skip silently when it is missing.
    target = Path(install_dir) / SERVICE_BINARY_NAME
    if target.exists() and shutil.which("fuser"):
        subprocess.run(
            ["fuser", "-k", "-TERM", str(target)],
            capture_output=True, text=True, env=env,
        )


def _step_mkdir(install_dir, log):
    os.makedirs(install_dir, exist_ok=True)
    # Settings dir: service (as root) persists default printer here
    os.makedirs(SETTINGS_DIR, exist_ok=True)

def _step_copy_service(install_dir, log):
    # The service binary is embedded in our PyInstaller bundle via
    # --add-binary and extracted into sys._MEIPASS at startup.
    src = BUNDLE_DIR / SERVICE_BINARY_NAME
    if not src.exists():
        raise FileNotFoundError(
            f"Service binary not found in installer bundle ({src}). "
            "The installer was built incorrectly — re-run the CI "
            "build-linux step."
        )
    dst = Path(install_dir) / SERVICE_BINARY_NAME
    log(f"  copy {SERVICE_BINARY_NAME}")
    shutil.copy2(src, dst)
    dst.chmod(0o755)

def _step_copy_gui(install_dir, log):
    # GUI script is embedded as a data file in the installer bundle.
    src = BUNDLE_DIR / GUI_SCRIPT_NAME
    if not src.exists():
        raise FileNotFoundError(
            f"GUI script not found in installer bundle ({src}). "
            "The installer was built incorrectly — re-run the CI "
            "build-linux step."
        )
    dst = Path(install_dir) / GUI_SCRIPT_NAME
    log(f"  copy {GUI_SCRIPT_NAME}")
    shutil.copy2(src, dst)
    dst.chmod(0o755)

    # Update-check helper lives beside the GUI so `import update_notifier`
    # resolves from the script's own directory. Best-effort: an installer
    # built without it (older CI) still produces a working install.
    src_helper = BUNDLE_DIR / UPDATE_HELPER_NAME
    if src_helper.exists():
        dst_helper = Path(install_dir) / UPDATE_HELPER_NAME
        log(f"  copy {UPDATE_HELPER_NAME}")
        shutil.copy2(src_helper, dst_helper)
        dst_helper.chmod(0o644)
    else:
        log(f"  ({UPDATE_HELPER_NAME} not in bundle — update checks disabled)")

def _step_apt_deps(install_dir, log):
    """
    Install GTK3 + AppIndicator runtime dependencies for the GUI.
    The GUI runs under the user's session (not as root), so we install
    the distro packages rather than pip-installing PyGObject into a venv.
    """
    env = _system_env()
    env["DEBIAN_FRONTEND"] = "noninteractive"

    log("  apt-get update")
    subprocess.run(["apt-get", "update"],
                   env=env, capture_output=True, text=True, timeout=120)

    # Core — GTK3 + GObject bindings.  Fatal if missing.
    core = ["python3", "python3-gi", "gir1.2-gtk-3.0"]
    log(f"  apt-get install -y {' '.join(core)}")
    r = subprocess.run(["apt-get", "install", "-y"] + core,
                       env=env, capture_output=True, text=True, timeout=300)
    for line in (r.stdout + r.stderr).splitlines():
        if line.strip():
            log(f"    {line}")
    if r.returncode != 0:
        detail = (r.stderr or r.stdout or "").strip() \
                 or f"exit status {r.returncode}"
        raise RuntimeError(f"apt-get install failed:\n{detail}")

    # Tray indicator: prefer Ayatana, fall back to legacy.  Best-effort;
    # the window still works without a tray icon.
    for pkg in ("gir1.2-ayatanaappindicator3-0.1", "gir1.2-appindicator3-0.1"):
        log(f"  apt-get install -y {pkg}")
        r = subprocess.run(["apt-get", "install", "-y", pkg],
                           env=env, capture_output=True, text=True, timeout=180)
        if r.returncode == 0:
            break
        log(f"    (skipped: {pkg} not available)")

    # GNOME extension — only required on GNOME sessions.  Optional.
    log("  apt-get install -y gnome-shell-extension-appindicator (optional)")
    subprocess.run(
        ["apt-get", "install", "-y", "gnome-shell-extension-appindicator"],
        env=env, capture_output=True, text=True, timeout=180,
    )

    # notify-send — transport for the daily update notification (plyer's
    # Linux backend and update_notifier's fallback both use it). Optional;
    # without it the GUI only loses the desktop notification.
    log("  apt-get install -y libnotify-bin (optional, update notifications)")
    subprocess.run(
        ["apt-get", "install", "-y", "libnotify-bin"],
        env=env, capture_output=True, text=True, timeout=180,
    )

def _step_polkit(install_dir, log):
    """
    Install a polkit rule so the desktop user can manage api-printer.service
    from the GUI without a password prompt.  polkit watches this directory
    via inotify and picks up the new rule immediately.
    """
    path = Path(POLKIT_RULE_PATH)
    log(f"  writing {path}")
    os.makedirs(path.parent, exist_ok=True)
    path.write_text(POLKIT_RULE)
    path.chmod(0o644)


def _step_desktop(install_dir, log):
    # Launcher on PATH — one-line wrapper around python3 + the GUI script.
    launcher_body = (
        "#!/bin/sh\n"
        f"exec python3 {install_dir}/{GUI_SCRIPT_NAME} \"$@\"\n"
    )
    log(f"  writing {LAUNCHER_PATH}")
    Path(LAUNCHER_PATH).write_text(launcher_body)
    Path(LAUNCHER_PATH).chmod(0o755)

    # Desktop entry: application menu + XDG autostart
    src_desktop = BUNDLE_DIR / DESKTOP_ENTRY_NAME
    if not src_desktop.exists():
        raise FileNotFoundError(
            f"Desktop entry not found in installer bundle ({src_desktop})."
        )
    for dst in (APPLICATIONS_DESKTOP_PATH, AUTOSTART_DESKTOP_PATH):
        log(f"  writing {dst}")
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src_desktop, dst)
        Path(dst).chmod(0o644)

    # Refresh the desktop DB so the entry shows up without a logout.
    if shutil.which("update-desktop-database"):
        log("  update-desktop-database /usr/share/applications")
        subprocess.run(
            ["update-desktop-database", "/usr/share/applications"],
            capture_output=True, text=True, env=_system_env(), timeout=30,
        )

def _system_env() -> dict:
    """
    Return a copy of os.environ with PyInstaller's LD_LIBRARY_PATH override
    undone, so that system binaries (systemctl, etc.) link against the
    system's own libcrypto / libsystemd instead of the older copies that
    PyInstaller extracted into /tmp/_MEI… beside our installer.

    PyInstaller preserves the caller's original value in LD_LIBRARY_PATH_ORIG
    when it hijacks LD_LIBRARY_PATH at bootstrap.
    """
    env = os.environ.copy()
    original = env.pop("LD_LIBRARY_PATH_ORIG", None)
    if original is not None:
        env["LD_LIBRARY_PATH"] = original
    else:
        env.pop("LD_LIBRARY_PATH", None)
    return env


def _step_systemd(install_dir, log):
    unit = Path("/etc/systemd/system/api-printer.service")
    log(f"  writing {unit}")
    unit.write_text(
        SERVICE_UNIT.format(
            install_dir=install_dir,
            service_binary=SERVICE_BINARY_NAME,
        )
    )
    env = _system_env()
    for cmd in [
        ["systemctl", "daemon-reload"],
        ["systemctl", "enable",  "api-printer.service"],
        ["systemctl", "restart", "api-printer.service"],
    ]:
        log(f"  {' '.join(cmd)}")
        result = subprocess.run(cmd, capture_output=True, text=True, env=env)
        for line in (result.stdout + result.stderr).splitlines():
            if line.strip():
                log(f"    {line}")
        if result.returncode != 0:
            detail = (result.stderr or result.stdout or "").strip() \
                     or f"exit status {result.returncode}"
            raise RuntimeError(
                f"`{' '.join(cmd)}` failed:\n{detail}"
            )


