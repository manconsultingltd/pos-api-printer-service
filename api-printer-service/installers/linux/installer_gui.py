RED_FAIL   = "#c0392b"


class InstallerApp:
    PAGE_WELCOME     = 0
    PAGE_CHECKS      = 1
    PAGE_DESTINATION = 2
    PAGE_INSTALLING  = 3
    PAGE_FINISH      = 4

    def __init__(self):
        import tkinter as tk
        from tkinter import ttk, filedialog, messagebox
        self._tk         = tk
        self._ttk        = ttk
        self._filedialog = filedialog
        self._messagebox = messagebox

        self.root = tk.Tk()
        self.root.title("API Printer Service — Setup")
        self.root.geometry("620x480")
        self.root.resizable(False, False)
        self.root.configure(bg=LIGHT_GRAY)

        # HiDPI / Wayland scaling: honour GDK_SCALE / QT_SCALE_FACTOR if set,
        # otherwise let Tk auto-detect via its own DPI query.
        try:
            scale = float(os.environ.get("GDK_SCALE") or
                          os.environ.get("QT_SCALE_FACTOR") or 1.0)
            if scale != 1.0:
                self.root.tk.call("tk", "scaling", scale * 1.33)
        except Exception:
            pass

        self.install_dir  = tk.StringVar(value=DEFAULT_INSTALL_DIR)
        self.current_page = -1

        self._build_chrome()
        self._show_page(self.PAGE_WELCOME)

    def run(self):
        self.root.mainloop()

    # ── Chrome ────────────────────────────────────────────────────────────────

    def _build_chrome(self):
        tk = self._tk
        hdr = tk.Frame(self.root, bg=DARK_BLUE, height=90)
        hdr.pack(fill="x")
        hdr.pack_propagate(False)
        tk.Label(hdr, text="⚙  API Printer Service",
                 font=("Helvetica", 20, "bold"),
                 fg="white", bg=DARK_BLUE).pack(side="left", padx=24, pady=24)
        tk.Label(hdr, text=f"Version {VERSION}",
                 font=("Helvetica", 10),
                 fg="#aaccee", bg=DARK_BLUE).place(relx=1.0, rely=1.0,
                                                    anchor="se", x=-16, y=-8)
        tk.Frame(self.root, bg=MID_BLUE, height=3).pack(fill="x")

        self.content = tk.Frame(self.root, bg=LIGHT_GRAY)
        self.content.pack(fill="both", expand=True)

        tk.Frame(self.root, bg="#cccccc", height=1).pack(fill="x")

        bar = tk.Frame(self.root, bg=LIGHT_GRAY, pady=10)
        bar.pack(fill="x")

        self.btn_cancel = tk.Button(bar, text="Cancel", width=10,
                                    command=self._on_cancel,
                                    relief="flat", bg="#e0e0e0", cursor="hand2")
        self.btn_cancel.pack(side="left", padx=16)

        self.btn_back = tk.Button(bar, text="◀  Back", width=10,
                                  command=self._on_back, state="disabled",
                                  relief="flat", bg="#e0e0e0", cursor="hand2")
        self.btn_back.pack(side="right", padx=6)

        self.btn_next = tk.Button(bar, text="Next  ▶", width=12,
                                  command=self._on_next,
                                  relief="flat", bg=MID_BLUE, fg="white",
                                  font=("Helvetica", 10, "bold"), cursor="hand2")
        self.btn_next.pack(side="right", padx=6)

    def _clear(self):
        for w in self.content.winfo_children():
            w.destroy()

    def _show_page(self, page):
        self._clear()
        self.current_page = page
        pages = {
            self.PAGE_WELCOME:     self._render_welcome,
            self.PAGE_CHECKS:      self._render_checks,
            self.PAGE_DESTINATION: self._render_destination,
            self.PAGE_INSTALLING:  self._render_installing,
            self.PAGE_FINISH:      self._render_finish,
        }
        pages[page]()

        self.btn_back.config(
            state="normal" if page in (self.PAGE_CHECKS, self.PAGE_DESTINATION)
            else "disabled")

        if page == self.PAGE_INSTALLING:
            self.btn_next.config(state="disabled", text="Installing…")
            self.btn_back.config(state="disabled")
            self.btn_cancel.config(state="disabled")
        elif page == self.PAGE_FINISH:
            self.btn_next.config(text="Finish", state="normal",
                                 command=self.root.destroy, bg=GREEN_OK)
            self.btn_back.config(state="disabled")
            self.btn_cancel.config(state="disabled")
        elif page == self.PAGE_CHECKS:
            blocked = bool(_checks_blocking(self._checks_list))
            self.btn_next.config(
                text="Next  ▶", command=self._on_next,
                state="disabled" if blocked else "normal",
                bg="#999999" if blocked else MID_BLUE,
            )
        else:
            self.btn_next.config(text="Next  ▶", command=self._on_next,
                                 state="normal", bg=MID_BLUE)

    # ── Pages ─────────────────────────────────────────────────────────────────

    def _render_welcome(self):
        tk = self._tk
        f  = tk.Frame(self.content, bg=LIGHT_GRAY, padx=36, pady=28)
        f.pack(fill="both", expand=True)
        tk.Label(f, text="Welcome to the API Printer Service Installer",
                 font=("Helvetica", 14, "bold"),
                 bg=LIGHT_GRAY, fg=DARK_BLUE).pack(anchor="w")
        tk.Frame(f, bg=MID_BLUE, height=2).pack(fill="x", pady=(8, 18))
        tk.Label(f, justify="left", wraplength=520, bg=LIGHT_GRAY,
                 font=("Helvetica", 10), text=(
            "This wizard will guide you through the installation of the\n"
            "API Printer Service on your Linux system.\n\n"
            "What will be installed:\n"
            "  •  Service binary → chosen install directory (self-contained)\n"
            "  •  Systemd unit   →  auto-starts on boot\n\n"
            "Click  Next  to choose the install location."
        )).pack(anchor="w")

    def _render_checks(self):
        tk = self._tk
        self._checks_list = _run_system_checks()
        blocked = _checks_blocking(self._checks_list)

        f = tk.Frame(self.content, bg=LIGHT_GRAY, padx=36, pady=20)
        f.pack(fill="both", expand=True)

        header = "System Compatibility"
        color  = RED_FAIL if blocked else DARK_BLUE
        tk.Label(f, text=header, font=("Helvetica", 14, "bold"),
                 bg=LIGHT_GRAY, fg=color).pack(anchor="w")
        tk.Frame(f, bg=(RED_FAIL if blocked else MID_BLUE),
                 height=2).pack(fill="x", pady=(8, 14))

        list_frame = tk.Frame(f, bg="white", relief="solid", bd=1)
        list_frame.pack(fill="both", expand=True)
        for c in self._checks_list:
            row = tk.Frame(list_frame, bg="white")
            row.pack(fill="x", padx=10, pady=4)
            icon, fg = {
                "ok":   ("✓", GREEN_OK),
                "warn": ("⚠", AMBER_WARN),
                "fail": ("✗", RED_FAIL),
            }[c.status]
            tk.Label(row, text=icon, fg=fg, bg="white",
                     font=("Helvetica", 12, "bold"), width=2
                     ).pack(side="left")
            tk.Label(row, text=c.name, bg="white",
                     font=("Helvetica", 10, "bold"), width=16, anchor="w"
                     ).pack(side="left")
            if c.message:
                tk.Label(row, text=c.message, bg="white",
                         font=("Helvetica", 9), fg="#444444",
                         wraplength=340, justify="left", anchor="w"
                         ).pack(side="left", fill="x", expand=True)

        footer = tk.Frame(f, bg=LIGHT_GRAY)
        footer.pack(fill="x", pady=(10, 0))
        if blocked:
            tk.Label(footer,
                     text="This system cannot run the service. "
                          "Address the failing check(s) above.",
                     bg=LIGHT_GRAY, fg=RED_FAIL,
                     font=("Helvetica", 9, "bold"),
                     ).pack(side="left")
        tk.Button(footer, text="Re-check", relief="flat", bg="#e0e0e0",
                  cursor="hand2",
                  command=lambda: self._show_page(self.PAGE_CHECKS),
                  ).pack(side="right")

    def _render_destination(self):
        tk = self._tk
        f  = tk.Frame(self.content, bg=LIGHT_GRAY, padx=36, pady=28)
        f.pack(fill="both", expand=True)
        tk.Label(f, text="Choose Install Location",
                 font=("Helvetica", 14, "bold"),
                 bg=LIGHT_GRAY, fg=DARK_BLUE).pack(anchor="w")
        tk.Frame(f, bg=MID_BLUE, height=2).pack(fill="x", pady=(8, 18))
        tk.Label(f, text="Install directory:", bg=LIGHT_GRAY,
                 font=("Helvetica", 10)).pack(anchor="w")
        row = tk.Frame(f, bg=LIGHT_GRAY)
        row.pack(fill="x", pady=(4, 0))
        tk.Entry(row, textvariable=self.install_dir, width=46,
                 font=("Helvetica", 10), relief="solid", bd=1).pack(side="left")
        tk.Button(row, text="Browse…", relief="flat", bg="#e0e0e0",
                  cursor="hand2", command=self._browse).pack(side="left", padx=8)
        tk.Label(f, text="\nRequired disk space: ~80 MB",
                 bg=LIGHT_GRAY, fg="#777777",
                 font=("Helvetica", 9)).pack(anchor="w")

    def _browse(self):
        d = self._filedialog.askdirectory(initialdir=self.install_dir.get())
        if d:
            self.install_dir.set(d)

    def _render_installing(self):
        tk, ttk = self._tk, self._ttk
        f = tk.Frame(self.content, bg=LIGHT_GRAY, padx=36, pady=20)
        f.pack(fill="both", expand=True)
        tk.Label(f, text="Installing…", font=("Helvetica", 14, "bold"),
                 bg=LIGHT_GRAY, fg=DARK_BLUE).pack(anchor="w")
        tk.Frame(f, bg=MID_BLUE, height=2).pack(fill="x", pady=(8, 14))

        self._prog_label = tk.Label(f, text="Preparing…", bg=LIGHT_GRAY,
                                    font=("Helvetica", 10), anchor="w")
        self._prog_label.pack(fill="x")
        self._prog_bar = ttk.Progressbar(f, orient="horizontal",
                                          mode="determinate", length=540)
        self._prog_bar.pack(pady=(6, 12))
        self._log_box = tk.Text(f, height=11, state="disabled",
                                bg="#1e1e1e", fg="#d4d4d4",
                                font=("Courier New", 9), relief="flat")
        self._log_box.pack(fill="both", expand=True)

        threading.Thread(target=self._do_install, daemon=True).start()

    def _log(self, msg):
        self._log_box.config(state="normal")
        self._log_box.insert("end", msg + "\n")
        self._log_box.see("end")
        self._log_box.config(state="disabled")
        self.root.update_idletasks()

    def _set_progress(self, pct, label):
        self._prog_bar["value"] = pct
        self._prog_label.config(text=label)
        self.root.update_idletasks()

    def _do_install(self):
        try:
            run_install_steps(
                self.install_dir.get(),
                log_fn=self._log,
                progress_fn=self._set_progress,
            )
            self.root.after(0, lambda: (
                self.btn_next.config(state="normal", text="Finish",
                                     bg=GREEN_OK,
                                     command=lambda: self._show_page(self.PAGE_FINISH))
            ))
        except Exception as exc:
            self._log(f"\n✗  Error: {exc}")
            self._set_progress(self._prog_bar["value"], "Installation failed.")
            self.root.after(0, lambda: self._messagebox.showerror(
                "Installation Failed",
                f"An error occurred:\n\n{exc}\n\n"
                "Make sure you ran this installer with sudo.",
            ))

    def _render_finish(self):
        tk = self._tk
        f  = tk.Frame(self.content, bg=LIGHT_GRAY, padx=36, pady=28)
        f.pack(fill="both", expand=True)
        tk.Label(f, text="Installation Complete  ✓",
                 font=("Helvetica", 14, "bold"),
                 bg=LIGHT_GRAY, fg=GREEN_OK).pack(anchor="w")
        tk.Frame(f, bg=GREEN_OK, height=2).pack(fill="x", pady=(8, 18))
        tk.Label(f, justify="left", bg=LIGHT_GRAY, font=("Courier New", 9),
                 text=(
            f"  Install directory : {self.install_dir.get()}\n"
            f"  Port              : http://localhost:5058\n"
            f"  Health check      : curl http://localhost:5058/health\n"
            f"  Logs              : {LOG_FILE}\n"
            f"  GUI launcher      : {LAUNCHER_PATH}\n"
            f"                      (also in the application menu)\n\n"
            f"  systemctl status  api-printer.service\n"
            f"  systemctl stop    api-printer.service\n"
        )).pack(anchor="w")

    # ── Navigation ────────────────────────────────────────────────────────────

    def _on_next(self):
        if self.current_page == self.PAGE_WELCOME:
            self._show_page(self.PAGE_CHECKS)
        elif self.current_page == self.PAGE_CHECKS:
            warnings = _checks_warnings(self._checks_list)
            if warnings and not self._messagebox.askyesno(
                "Warnings",
                "Some checks produced warnings:\n\n"
                + "\n".join(f"• {c.name}: {c.message}" for c in warnings)
                + "\n\nContinue anyway?",
            ):
                return
            self._show_page(self.PAGE_DESTINATION)
        elif self.current_page == self.PAGE_DESTINATION:
            if not self.install_dir.get().strip():
                self._messagebox.showwarning("No directory",
                                             "Please enter an install directory.")
                return
            self._show_page(self.PAGE_INSTALLING)

    def _on_back(self):
        if self.current_page == self.PAGE_CHECKS:
            self._show_page(self.PAGE_WELCOME)
        elif self.current_page == self.PAGE_DESTINATION:
            self._show_page(self.PAGE_CHECKS)

    def _on_cancel(self):
        if self._messagebox.askyesno("Cancel", "Cancel installation?"):
            self.root.destroy()


