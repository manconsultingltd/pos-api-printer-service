"""
API Printer Service — Linux Installer
Runs as a Tkinter GUI wizard when a display is available, or as a
step-by-step terminal wizard when running headless / over SSH.

Supports X11 and Wayland (via XWayland).  Works on Debian 12/13 and
Ubuntu 22.04/24.04.  Must be run as root (sudo or pkexec).
"""

