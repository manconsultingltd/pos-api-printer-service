# =============================================================================
# System compatibility checks
# =============================================================================

class Check(NamedTuple):
    name: str
    status: str   # "ok" | "warn" | "fail"
    message: str = ""


def _system_glibc() -> str | None:
    """Return the running system's glibc version (e.g. '2.39')."""
    try:
        return os.confstr("CS_GNU_LIBC_VERSION").split()[-1]
    except (AttributeError, ValueError, OSError):
        return None


def _binary_required_glibc(binary_path: Path) -> str | None:
    """Scan an ELF binary for the highest GLIBC_x.y symbol version it needs."""
    try:
        data = binary_path.read_bytes()
    except OSError:
        return None
    versions = [m.decode() for m in re.findall(rb"GLIBC_(\d+\.\d+)", data)]
    if not versions:
        return None
    return max(versions, key=lambda v: tuple(int(x) for x in v.split(".")))


def _version_ge(a: str, b: str) -> bool:
    return tuple(int(x) for x in a.split(".")) >= tuple(int(x) for x in b.split("."))


def _run_system_checks() -> list[Check]:
    """
    Run pre-install compatibility checks.  Returns a list of Check tuples.
    Any Check with status="fail" blocks installation; "warn" asks the user
    to confirm; "ok" is silent-pass.
    """
    checks: list[Check] = []

    # Platform
    if sys.platform.startswith("linux"):
        checks.append(Check("Operating system", "ok", "Linux"))
    else:
        checks.append(Check("Operating system", "fail",
                            f"Requires Linux; detected {sys.platform}"))

    # CPU architecture — the embedded binary is x86_64
    arch = platform.machine()
    if arch in ("x86_64", "amd64"):
        checks.append(Check("CPU architecture", "ok", arch))
    else:
        checks.append(Check("CPU architecture", "fail",
                            f"Requires x86_64; detected {arch}"))

    # glibc — compare the system's version against what the bundled
    # service binary actually links against (read from the ELF itself).
    binary = BUNDLE_DIR / SERVICE_BINARY_NAME
    required = _binary_required_glibc(binary) if binary.exists() else None
    system = _system_glibc()
    if required and system:
        if _version_ge(system, required):
            checks.append(Check("glibc", "ok",
                                f"system {system} ≥ required {required}"))
        else:
            checks.append(Check("glibc", "fail",
                                f"need glibc ≥ {required}, system has {system} "
                                "— upgrade to Debian 13 or Ubuntu 24.04"))
    elif system:
        checks.append(Check("glibc", "warn",
                            f"system {system}; could not read required version "
                            "from embedded binary"))
    else:
        checks.append(Check("glibc", "warn",
                            "could not determine system glibc version"))

    # systemd — we write a .service unit and enable it
    if not shutil.which("systemctl"):
        checks.append(Check("systemd", "fail", "systemctl not found on PATH"))
    elif not Path("/run/systemd/system").exists():
        checks.append(Check("systemd", "fail",
                            "systemd is not the active init "
                            "(no /run/systemd/system)"))
    else:
        checks.append(Check("systemd", "ok", ""))

    # CUPS — warning only; user can install it afterwards.  The service
    # shells out to lpstat/lpr/cancel at runtime, so without CUPS it
    # starts but every print request fails.
    if shutil.which("lpstat"):
        checks.append(Check("CUPS", "ok", ""))
    else:
        checks.append(Check("CUPS", "warn",
                            "lpstat not found — install with "
                            "`apt install cups` before printing"))

    # Port 5058 — the service binds here.  If our own systemd unit is
    # holding it, we treat that as OK: the install flow stops the service
    # before overwriting the binary and restarts it at the end.  Only an
    # *unrelated* process on the port warrants a warning.
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            s.bind(("127.0.0.1", 5058))
        checks.append(Check("Port 5058", "ok", ""))
    except OSError as e:
        if _existing_service_is_active():
            checks.append(Check("Port 5058", "ok",
                                "held by existing api-printer.service "
                                "(installer will stop and restart it)"))
        else:
            checks.append(Check("Port 5058", "warn",
                                f"already in use ({e.strerror}); service will "
                                "fail to start until the port is freed"))

    return checks


def _existing_service_is_active() -> bool:
    """True if the previously-installed api-printer.service is running."""
    if not shutil.which("systemctl"):
        return False
    r = subprocess.run(
        ["systemctl", "is-active", "api-printer.service"],
        capture_output=True, text=True, env=_system_env(),
    )
    return r.stdout.strip() == "active"


def _checks_blocking(checks: list[Check]) -> list[Check]:
    return [c for c in checks if c.status == "fail"]


def _checks_warnings(checks: list[Check]) -> list[Check]:
    return [c for c in checks if c.status == "warn"]


# =============================================================================
# Display detection — handles sudo-stripped env vars + Wayland
# =============================================================================

def _restore_display_from_proc() -> None:
    """
    When the installer is invoked with ``sudo ./installer``, the kernel
    strips DISPLAY / WAYLAND_DISPLAY / XAUTHORITY / XDG_RUNTIME_DIR.
    Walk up /proc/<pid>/environ to find them in a parent process that
    still has a live graphical session.

    This is Linux-only and completely safe: we are already root, so
    /proc/<pid>/environ is readable for any PID.
    """
    needed = {"DISPLAY", "WAYLAND_DISPLAY", "XAUTHORITY", "XDG_RUNTIME_DIR"}
    # Nothing to do if we already have at least a display variable
    if os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"):
        return

    pid = os.getppid()
    for _ in range(10):          # look at most 10 levels up the tree
        try:
            env_raw = Path(f"/proc/{pid}/environ").read_bytes()
        except OSError:
            break

        found: dict[str, str] = {}
        for entry in env_raw.split(b"\x00"):
            if b"=" in entry:
                k, _, v = entry.partition(b"=")
                try:
                    found[k.decode()] = v.decode()
                except UnicodeDecodeError:
                    pass

        for var in needed:
            if var in found and var not in os.environ:
                os.environ[var] = found[var]

        if os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"):
            return           # found what we needed

        # Move to parent PID
        try:
            stat = Path(f"/proc/{pid}/stat").read_text()
            # Format: pid (comm) state ppid ...
            after_comm = stat.split(")", 1)[1]
            ppid = int(after_comm.split()[1])
        except (OSError, IndexError, ValueError):
            break
        if ppid <= 1:
            break
        pid = ppid


def _has_display() -> bool:
    """Return True if a graphical display is reachable by Tkinter."""
    # Attempt to recover display vars stripped by sudo
    if os.geteuid() == 0:
        _restore_display_from_proc()

    if not os.environ.get("DISPLAY") and not os.environ.get("WAYLAND_DISPLAY"):
        return False

    # Tkinter uses XWayland on Wayland sessions — a $DISPLAY is still needed.
    # If only WAYLAND_DISPLAY is set (no XWayland), Tk would fail.
    # The actual probe below catches that case.
    try:
        import tkinter as tk
        root = tk.Tk()
        root.withdraw()   # hide the test window immediately
        root.destroy()
        return True
    except Exception:
        return False


